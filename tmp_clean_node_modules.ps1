$ErrorActionPreference = "Continue"
$sys32 = Join-Path $env:WINDIR "System32"
$env:PATH = "$sys32;$env:WINDIR;" + $env:PATH
$cmd = Join-Path $sys32 "cmd.exe"

function Remove-JunctionOrSymlink([string]$path) {
  if (-not (Test-Path -LiteralPath $path)) { return }
  Write-Host "rmdir $path"
  & $cmd /c "rmdir `"$path`""
  if (Test-Path -LiteralPath $path) {
    Write-Host "fallback Remove-Item $path"
    Remove-Item -LiteralPath $path -Force -ErrorAction SilentlyContinue
  }
}

$root = Get-Location
$dirs = @(
  (Join-Path $root "node_modules"),
  (Join-Path $root "sdk\typescript\node_modules")
)

foreach ($dir in $dirs) {
  if (-not (Test-Path -LiteralPath $dir)) { continue }
  Get-ChildItem -LiteralPath $dir -Force -Recurse -ErrorAction SilentlyContinue |
    Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint } |
    Sort-Object { $_.FullName.Length } -Descending |
    ForEach-Object { Remove-JunctionOrSymlink $_.FullName }
}

foreach ($dir in $dirs) {
  if (Test-Path -LiteralPath $dir) {
    Write-Host "Remove-Item $dir"
    Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
    if (Test-Path -LiteralPath $dir) {
      Write-Host "FAILED $dir"
      Get-ChildItem -LiteralPath $dir -Force -Recurse -ErrorAction SilentlyContinue | Select-Object FullName, Attributes
    } else {
      Write-Host "removed $dir"
    }
  } else {
    Write-Host "already gone $dir"
  }
}
